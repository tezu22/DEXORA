#!/usr/bin/env python3
"""Regenerate data/catalog.js from data/catalog.json after editing the catalog."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'data'/'catalog.json').read_text(encoding='utf8'))
expected={'cpu','board','ram','gpu','ssd','cooler','case','psu'}
assert set(data)==expected, 'Invalid catalog categories'
seen=set()
for cat,group in data.items():
    assert isinstance(group,list)
    for row in group:
        assert isinstance(row.get('id'),str) and isinstance(row.get('name'),str)
        key=(cat,row['id']);assert key not in seen,key;seen.add(key)
        if row.get('price') is not None:assert isinstance(row['price'],int) and row['price']>0
(root/'data'/'catalog.js').write_text('/* Generated from catalog.json. Do not edit this file directly. */\nwindow.NEON_CATALOG = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n',encoding='utf8')
print(f'Exported {len(seen)} catalog entries to data/catalog.js')
